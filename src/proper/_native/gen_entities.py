"""Writes `proper_entities.inc`: the named character references of HTML5
(`html.entities.html5`, the table `html.unescape` uses) for `proper_text.pas`.

    uv run python src/proper/_native/gen_entities.py

The keys are sorted by their bytes, for a binary search; a key and its
value are each an offset and a length into one array of bytes.
`ENTITY_FIRST[c]` is the first key that starts with the byte `c` (or a
later byte), so a search starts with the keys of its first letter.
"""
from html.entities import html5
from pathlib import Path


HERE = Path(__file__).parent


def byte_array(name: str, data: bytes) -> str:
    rows = [
        "    " + ", ".join(str(b) for b in data[i:i + 24])
        for i in range(0, len(data), 24)
    ]
    return f"  {name}: array[0..{len(data) - 1}] of Byte = (\n" + ",\n".join(rows) + "\n  );\n"


def word_array(name: str, values: "list[int]") -> str:
    rows = [
        "    " + ", ".join(str(v) for v in values[i:i + 16])
        for i in range(0, len(values), 16)
    ]
    return f"  {name}: array[0..{len(values) - 1}] of Word = (\n" + ",\n".join(rows) + "\n  );\n"


def generate() -> str:
    items = sorted((key.encode("ascii"), value.encode("utf-8")) for key, value in html5.items())
    keys = values = b""
    key_at, value_at = [0], [0]
    for key, value in items:
        keys += key
        values += value
        key_at.append(len(keys))
        value_at.append(len(values))
    first = [
        next((i for i, (key, _) in enumerate(items) if key[0] >= c), len(items))
        for c in range(257)
    ]
    return (
        "{ Generated by gen_entities.py from html.entities.html5: don't edit. }\n"
        "const\n"
        f"  ENTITY_COUNT = {len(items)};\n"
        + word_array("ENTITY_FIRST", first)
        + byte_array("ENTITY_KEYS", keys)
        + word_array("ENTITY_KEY_AT", key_at)
        + byte_array("ENTITY_VALUES", values)
        + word_array("ENTITY_VALUE_AT", value_at)
    )


if __name__ == "__main__":
    out = HERE / "proper_entities.inc"
    out.write_text(generate())
    print(out)
