"""
minijx runtime: a catalog of compiled components, with the same API shape as
`jx.Catalog`.

    catalog = Catalog("components/", compiler="minijx", site_name="Demo")
    catalog.compile()
    html = catalog.render("pages/home.jx", globals={"user": user}, title="Hi")

A component is named by its path relative to one of the folders, as in Jx:
`"pages/home.jx"`. The catalog finds the Python module minijx generated for
it (`pages/home.py`; `sitemap.xml.jx` -> `sitemap_xml.py`), loads it once,
and calls its `render`.

With `auto_reload=True` (the default) every render checks the modification
times of the module and of every `.jx` copied into it (the module's
`SOURCES`). A changed module is reloaded. A module older than its sources is
recompiled when `compiler` is given, and is an error otherwise.

With autoescape (on by default for `.jx`, `.html.jx` and `.xml.jx` files),
`{{ }}` escapes what it renders, as Jx does, and `render` returns `Markup`.
"""

